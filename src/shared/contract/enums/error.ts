/**
 * 错误码取值域。
 *
 * ## 为什么必须集中声明
 *
 * 一次采集失败的码要穿过四个地方：**主链产出**（`domain/crawl.ts`）、
 * **调度器与平台健康度读它做判断**（`scheduler/index.ts`、`platform/health.ts`）、
 * **`text/error-text.ts` 把它翻成人话**、**界面显示人话**。
 *
 * 而它曾经**只以字符串字面量的形式散在这四处** —— 拼错一个不会有任何编译报错，
 * 只会静默落到"未知原因"（用户看到一句没用的提示，而写码的人以为已经处理过了）。
 * 实测就有一次：仓储层写入的 `ORPHANED` 从来没被翻译过。
 *
 * ## 关于"认得出但没人写"的码
 *
 * `RATE_LIMITED` / `RISK` / `QUOTA_REACHED` / `OFFLINE` 目前没有产出点，
 * 但**历史库里的 `crawl_run.error_code` 可能留着它们**（旧版本写过），
 * 所以它们仍必须被归类 —— 把这些码删掉只会让老记录显示成"未知原因"。
 * 它们是有意保留的，不是遗漏。
 */

/** 采集失败的原因（落在 `crawl_run.error_code`）。 */
export const CRAWL_FAILURE_CODES = [
  // ── 主链产出 ──────────────────────────────────────────────
  /** 页面打开了，但一条都没解析出来（通常是选择器失效，也可能是"真的没有结果"）。 */
  'NO_RECORDS',
  /**
   * 解析出了记录，但**全都没有平台岗位 id**（身份键）—— 一条都没写。
   *
   * 与 `NO_RECORDS` 分开是有意的：这一轮的 `found` 看起来是正常的（甚至 20 条），
   * 只有身份键没了。写进去的后果不是"少几条"，而是**整页互相覆盖**（第一张卡插入、
   * 其余每一张都更新那一行）—— 必须是一个能一眼看出来的独立原因。
   */
  'NO_IDENTITY',
  /** 解析脚本在页面里抛错（选择器或脚本被改坏了）。 */
  'PARSE_FAILED',
  /** 连搜索页都没打开成功（网络 / 导航问题）。 */
  'NAVIGATION_FAILED',
  /** 命中登录墙（§7 点名的坑：绝不允许当作"没有新岗位"）。 */
  'NOT_LOGGED_IN',
  /** 其它风控信号（频控、验证码、异常跳转）。 */
  'BLOCKED',
  /** 平台侧今日额度耗尽 —— 退避重试没有意义。 */
  'PLATFORM_QUOTA',
  /** 适配器处于降级/失效（只解析不写库）。 */
  'PLATFORM_PAUSED',
  /** 到单轮预算上限主动停手（已抓到的照常入库；不是故障，是保险丝生效）。 */
  'DEADLINE_REACHED',
  /** 进程中途退出留下的半截记录（由仓储层在启动时补写）。 */
  'ORPHANED',
  // ── 历史值：只在旧库里出现，仍须能翻译 ──────────────────────
  'RATE_LIMITED',
  'RISK',
  'QUOTA_REACHED',
  'OFFLINE',
] as const

export type CrawlFailureCode = (typeof CRAWL_FAILURE_CODES)[number]
